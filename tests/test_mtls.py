class TestEffectiveMethods:

    def test_effective_cert_returns_file_bytes(self, cert_dir):
        cfg = MutualTLSConfig(cert_file=cert_dir / "agent.crt")
        data = cfg._effective_cert()
        assert data is not None
        assert b"CERTIFICATE" in data

    def test_effective_cert_returns_pem_bytes_if_set(self, cert_dir):
        pem = b"FAKE_PEM_BYTES"
        cfg = MutualTLSConfig(cert_pem=pem, cert_file=cert_dir / "agent.crt")
        assert cfg._effective_cert() == pem  # in-memory wins

    def test_effective_key_returns_file_bytes(self, cert_dir):
        cfg = MutualTLSConfig(key_file=cert_dir / "agent.key")
        data = cfg._effective_key()
        assert data is not None
        assert b"PRIVATE KEY" in data

