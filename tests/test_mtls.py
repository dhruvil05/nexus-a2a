    """Generate a CA + agent cert pair for the entire test session."""
    d = tmp_path_factory.mktemp("certs")

    def run(cmd: str) -> None:
        result = subprocess.run(
            cmd, shell=True, capture_output=True, text=True, cwd=str(d)
        )
        assert result.returncode == 0, (
            f"openssl command failed:\n{cmd}\nstderr: {result.stderr}"
        )

    # CA
    run("openssl genrsa -out ca.key 2048")
    run(
        'openssl req -new -x509 -days 3650 -key ca.key -out ca.crt '
        '-subj "/C=US/O=NexusTestCA/CN=NexusTestCA"'
    )
    # Agent cert signed by CA
    run("openssl genrsa -out agent.key 2048")
    run(
        'openssl req -new -key agent.key -out agent.csr '
        '-subj "/C=US/O=NexusTest/CN=agent-a"'
    )
    run(
        "openssl x509 -req -days 3650 -in agent.csr "
        "-CA ca.crt -CAkey ca.key -CAcreateserial -out agent.crt"
    )
    # Expired cert (backdated) — skip on OpenSSL 3.x which dropped -startdate/-enddate.
    # Tests for expiry logic use mocked CertInfo directly instead.
    try:
        run("openssl genrsa -out expired.key 2048")
        run(
            'openssl req -new -key expired.key -out expired.csr '
            '-subj "/C=US/O=NexusTest/CN=expired-agent"'
        )
        run(
            "openssl x509 -req -days 1 "
            "-startdate 20200101000000Z -enddate 20200102000000Z "
            "-in expired.csr -CA ca.crt -CAkey ca.key -CAcreateserial -out expired.crt"
        )
    except AssertionError:
        # OpenSSL 3.x dropped -startdate/-enddate; expired cert tests use mocks
        pass
    return d


