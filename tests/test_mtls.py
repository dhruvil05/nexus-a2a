        cfg = MutualTLSConfig(
            cert_file=cert_dir / "agent.crt",
            key_file=cert_dir  / "agent.key",
            verify_client=True,
        )
        with pytest.raises(MtlsConfigError, match="CA"):
            cfg.validate()

