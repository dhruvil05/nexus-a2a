class TestCertInfo:

    def test_str_not_expired(self):
        info = CertInfo(
            subject="CN=agent-a",
            issuer="CN=CA",
            not_before=datetime(2024, 1, 1, tzinfo=timezone.utc),
            not_after=datetime(2035, 1, 1, tzinfo=timezone.utc),
            serial="ABCD",
            days_remaining=100,
            is_expired=False,
        )
        s = str(info)
        assert "agent-a" in s
        assert "100d remaining" in s

    def test_str_expired(self):
        info = CertInfo(
            subject="CN=old-agent",
            issuer="CN=CA",
            not_before=datetime(2020, 1, 1, tzinfo=timezone.utc),
            not_after=datetime(2020, 1, 2, tzinfo=timezone.utc),
            serial="0001",
            days_remaining=-100,
            is_expired=True,
        )
        assert "EXPIRED" in str(info)

    def test_san_default_empty(self):
        info = CertInfo(
            subject="CN=a",
            issuer="CN=ca",
            not_before=datetime.now(timezone.utc),
            not_after=datetime.now(timezone.utc),
            serial="01",
        )
        assert info.san == []


